function run(command, args, cwd) {
  return new Promise((resolvePromise, reject) => {
    const child = spawn(command, args, { cwd, stdio: 'inherit' });
    child.once('error', reject);
    child.once('exit', (code) => code === 0 ? resolvePromise() : reject(new Error(`${command} exited with ${code}`)));
  });
}

export function sha256(content) {
  return createHash('sha256').update(content).digest('hex');
}

export function normalizeAssetId(fileName) {
  return basename(fileName, '.svg').toLowerCase().replace(/[^a-z0-9-]+/g, '-').replace(/-{2,}/g, '-').replace(/^-|-$/g, '');
}

export function inspectSvg(source, fileName = 'asset.svg') {
  const failures = [];
  if (!source.trim()) failures.push('empty file');
  if (!/^\s*(?:<\?xml[^>]*>\s*)?(?:<!--[^]*?-->\s*)*<svg\b/i.test(source) || !/<\/svg>\s*$/i.test(source)) failures.push('invalid SVG root');
  const forbiddenElements = ['script', 'foreignObject', 'iframe', 'object', 'embed'];
  for (const element of forbiddenElements) if (new RegExp(`<\\s*${element}\\b`, 'i').test(source)) failures.push(`forbidden <${element}>`);
  if (/\s(?:on[a-z]+)\s*=/i.test(source)) failures.push('event handler attribute');
  if (/javascript\s*:/i.test(source)) failures.push('javascript URL');
  if (/@import\s+(?:url\s*\()?\s*['"]?https?:/i.test(source)) failures.push('external CSS import');
  if (/(?:href|src)\s*=\s*['"]\s*https?:/i.test(source) || /url\(\s*['"]?https?:/i.test(source)) failures.push('external resource');
  const tags = source.replace(/<!--[\s\S]*?-->|<\?[^]*?\?>|<!\[CDATA\[[\s\S]*?\]\]>/g, '').match(/<\/?[A-Za-z][^>]*>/g) ?? [];
  const stack = [];
  for (const tag of tags) {
    const match = tag.match(/^<\s*(\/?)\s*([\w:-]+)/);
    if (!match || tag.endsWith('/>')) continue;
    const [, closing, name] = match;
    if (!closing) stack.push(name);
    else if (stack.pop() !== name) failures.push(`malformed XML near </${name}>`);
  }
  if (stack.length) failures.push(`unclosed <${stack.at(-1)}>`);
  return { fileName, safe: failures.length === 0, failures: [...new Set(failures)] };
}

function parseUpstreamMetadata(source) {
  const categories = new Map();
  const mapBody = source.match(/const categoryMap[^=]*=\s*\{([\s\S]*?)\n\};/)?.[1] ?? '';
  for (const match of mapBody.matchAll(/'([^']+)'\s*:\s*'([^']+)'/g)) categories.set(`clawd-${match[1]}`, CATEGORY_MAP[match[2]] ?? 'uncategorized');
  return categories;
}

function humanize(id) {
  return LABEL_OVERRIDES[id] ?? id.replace(/^clawd-/, '').split('-').map((part) => part ? part[0].toUpperCase() + part.slice(1) : part).join(' ');
}

function isAnimatedSvg(source) {
  return /<(?:animate|animateTransform|animateMotion)\b|@keyframes\b|animation(?:-name)?\s*:/i.test(source);
}

function renderManifest(assets) {
  return `/* This file is generated by scripts/sync-clawd-pets.mjs. Do not edit manually. */\n\nexport type ClawdAssetCategory = 'emotion' | 'activity' | 'working' | 'status' | 'http' | 'special' | 'uncategorized';\n\nexport interface ClawdLibraryAsset {\n  id: string;\n  fileName: string;\n  label: string;\n  src: string;\n  category: ClawdAssetCategory;\n  keywords: string[];\n  animated: boolean;\n  hash: string;\n  source: 'upstream';\n}\n\nexport const CLAWD_LIBRARY_MANIFEST: readonly ClawdLibraryAsset[] = ${JSON.stringify(assets, null, 2)} as const;\n`;
}

async function readJson(path) {
  try { return JSON.parse(await readFile(path, 'utf8')); } catch { return null; }
}

async function listSvg(directory) {
  if (!existsSync(directory)) return [];
  return (await readdir(directory)).filter((file) => file.toLowerCase().endsWith('.svg')).sort();
}

async function collectAssets(repoRoot) {
  const sourceDir = join(repoRoot, 'public/pets');
  const metadata = parseUpstreamMetadata(await readFile(join(repoRoot, 'src/lib/pets.ts'), 'utf8'));
  const names = await listSvg(sourceDir);
  const seenIds = new Set();
  const seenHashes = new Map();
  const accepted = [];
  const rejected = [];
  const duplicates = [];
  for (const fileName of names) {
    const source = await readFile(join(sourceDir, fileName), 'utf8');
    const inspection = inspectSvg(source, fileName);
    if (!inspection.safe) { rejected.push(inspection); continue; }
    const id = normalizeAssetId(fileName);
    if (!id || seenIds.has(id)) { rejected.push({ fileName, safe: false, failures: ['duplicate or invalid id'] }); continue; }
    seenIds.add(id);
    const hash = sha256(source);
    const canonical = seenHashes.get(hash);
    if (canonical) duplicates.push({ fileName, duplicateOf: canonical, hash });
    else seenHashes.set(hash, fileName);
    const category = metadata.get(id) ?? (id.startsWith('clawd-working-') ? 'working' : 'activity');
    accepted.push({ id, fileName, label: humanize(id), src: `/vendor/clawd-pet/pets/${encodeURIComponent(fileName)}`, category, keywords: id.replace(/^clawd-/, '').split('-'), animated: isAnimatedSvg(source), hash, source: 'upstream' });
  }
  return { sourceDir, accepted, rejected, duplicates };
}

async function fileHash(path) {
  try { return sha256(await readFile(path)); } catch { return null; }
}

async function compareVendor(assets) {
  const current = join(VENDOR_ROOT, 'pets');
  const currentNames = await listSvg(current);
  const expectedNames = new Set(assets.map((asset) => asset.fileName));
  const report = { added: [], updated: [], unchanged: [], removedCandidates: currentNames.filter((name) => !expectedNames.has(name)) };
  for (const asset of assets) {
    const existingHash = await fileHash(join(current, asset.fileName));
    if (!existingHash) report.added.push(asset.fileName);
    else if (existingHash === asset.hash) report.unchanged.push(asset.fileName);
    else report.updated.push(asset.fileName);
  }
  return report;
}

async function localConflicts(assets) {
  const directory = join(ROOT, 'src/assets/clawd');
  if (!existsSync(directory)) return [];
  const output = [];
  for (const asset of assets) {
    const localPath = join(directory, asset.fileName);
    if (!existsSync(localPath)) continue;
    const localHash = await fileHash(localPath);
    if (localHash !== asset.hash) output.push({ id: asset.id, localPath: `src/assets/clawd/${asset.fileName}`, localHash, upstreamHash: asset.hash });
  }
  return output;
}

async function cloneAt(ref, tempRoot) {
  const repo = join(tempRoot, 'repo');
  await run('git', ['clone', '--quiet', '--filter=blob:none', '--no-checkout', REPOSITORY, repo], ROOT);
  await run('git', ['checkout', '--quiet', ref], repo);
  const commit = await new Promise((resolvePromise, reject) => {
    const child = spawn('git', ['rev-parse', 'HEAD'], { cwd: repo }); let output = '';
    child.stdout.on('data', (chunk) => { output += chunk; }); child.once('error', reject);
    child.once('exit', (code) => code === 0 ? resolvePromise(output.trim()) : reject(new Error('Unable to resolve upstream commit')));
  });
  return { repo, commit };
}

async function replaceVendor({ repo, commit, assets, report }) {
  const parent = dirname(VENDOR_ROOT);
  await mkdir(parent, { recursive: true });
  const stage = await mkdtemp(join(parent, '.clawd-pet-stage-'));
  const stagePets = join(stage, 'pets');
  await mkdir(stagePets, { recursive: true });
  if (existsSync(join(VENDOR_ROOT, 'pets'))) await cp(join(VENDOR_ROOT, 'pets'), stagePets, { recursive: true });
  for (const asset of assets) await copyFile(join(repo, 'public/pets', asset.fileName), join(stagePets, asset.fileName));
  await copyFile(join(repo, 'LICENSE'), join(stage, 'LICENSE'));
  await writeFile(join(stage, 'UPSTREAM.json'), `${JSON.stringify({ repository: 'abderrahimghazali/clawd-pet', commit, syncedAt: new Date().toISOString(), license: 'MIT', assetCount: (await listSvg(stagePets)).length }, null, 2)}\n`);
  const backup = `${VENDOR_ROOT}.backup-${process.pid}`;
  try {
    if (existsSync(VENDOR_ROOT)) await rename(VENDOR_ROOT, backup);
    await rename(stage, VENDOR_ROOT);
    await rm(backup, { recursive: true, force: true });
  } catch (error) {
    if (!existsSync(VENDOR_ROOT) && existsSync(backup)) await rename(backup, VENDOR_ROOT);
    throw error;
  }
  await mkdir(dirname(GENERATED_FILE), { recursive: true });
  const generatedTemp = `${GENERATED_FILE}.tmp-${process.pid}`;
  await writeFile(generatedTemp, renderManifest(assets));
  await rename(generatedTemp, GENERATED_FILE);
  return report;
}

export async function synchronize({ check = false, ref } = {}) {
  const recorded = await readJson(join(VENDOR_ROOT, 'UPSTREAM.json'));
  const pinnedRef = ref ?? recorded?.commit ?? DEFAULT_PINNED_REF;
  const tempRoot = await mkdtemp(join(tmpdir(), 'lunartide-clawd-sync-'));
  try {
    const { repo, commit } = await cloneAt(pinnedRef, tempRoot);
    const collected = await collectAssets(repo);
    if (collected.rejected.length) throw new Error(`Rejected ${collected.rejected.length} unsafe or invalid SVG files: ${JSON.stringify(collected.rejected)}`);
    const report = await compareVendor(collected.accepted);
    const conflicts = await localConflicts(collected.accepted);
    const manifest = renderManifest(collected.accepted);
    const currentManifest = existsSync(GENERATED_FILE) ? await readFile(GENERATED_FILE, 'utf8') : '';
    const drift = report.added.length + report.updated.length + report.removedCandidates.length + (manifest === currentManifest ? 0 : 1);
    const result = { commit, assetCount: collected.accepted.length, duplicates: collected.duplicates, rejected: collected.rejected, conflicts, ...report, manifestDrift: manifest !== currentManifest };
    console.log(JSON.stringify(result, null, 2));
    if (check) {
      if (drift) process.exitCode = 1;
      return result;
    }
    await replaceVendor({ repo, commit, assets: collected.accepted, report });
    return result;
  } finally {
    await rm(tempRoot, { recursive: true, force: true });
  }
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const args = process.argv.slice(2);
  const refIndex = args.indexOf('--ref');
  const ref = refIndex >= 0 ? args[refIndex + 1] : undefined;
  if (refIndex >= 0 && !ref) throw new Error('--ref requires a commit or tag');
  await synchronize({ check: args.includes('--check'), ref });
}
