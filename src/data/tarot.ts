export const FULL_DECK: TarotCard[] = [...MAJOR_ARCANA, ...MINOR];
export const MAJOR_ONLY: TarotCard[] = [...MAJOR_ARCANA];

export function shuffleDeck(): TarotCard[] {
  const deck = [...FULL_DECK];
  for (let i = deck.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [deck[i], deck[j]] = [deck[j], deck[i]];
  }
  return deck;
}

export function drawCards(count: 1 | 3): Array<{ card: TarotCard; reversed: boolean }> {
  const deck = shuffleDeck();
  return deck.slice(0, count).map((card) => ({
    card,
    reversed: Math.random() < 0.5,
  }));
}
