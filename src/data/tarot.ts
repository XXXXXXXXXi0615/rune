const SUIT_NAMES = {
  wands: { zh:'權杖', en:'Wands', element:'火' },
  cups: { zh:'聖杯', en:'Cups', element:'水' },
  swords: { zh:'寶劍', en:'Swords', element:'風' },
  pentacles: { zh:'錢幣', en:'Pentacles', element:'土' },
};

const RANK_NAMES = [
  { zh:'王牌', en:'Ace' }, { zh:'二', en:'Two' }, { zh:'三', en:'Three' },
  { zh:'四', en:'Four' }, { zh:'五', en:'Five' }, { zh:'六', en:'Six' },
  { zh:'七', en:'Seven' }, { zh:'八', en:'Eight' }, { zh:'九', en:'Nine' },
  { zh:'十', en:'Ten' }, { zh:'侍者', en:'Page' }, { zh:'騎士', en:'Knight' },
  { zh:'皇后', en:'Queen' }, { zh:'國王', en:'King' },
];

type Suit = 'wands' | 'cups' | 'swords' | 'pentacles';

function makeMinor(suit: Suit, index: number, zhKw: string[], enKw: string[], up: string, rev: string): TarotCard {
  const suitInfo = SUIT_NAMES[suit];
  const rank = RANK_NAMES[index];
  return {
    id: `${rank.en.toLowerCase()}-of-${suit}`,
    nameZh: `${suitInfo.zh}${rank.zh}`,
    nameEn: `${rank.en} of ${suitInfo.en}`,
    arcana:'minor', suit, number: index + 1,
    keywords: [...zhKw, suitInfo.element],
    uprightMeaning: up,
    reversedMeaning: rev,
  };
}

